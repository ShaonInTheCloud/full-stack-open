const { test } = require('node:test')
const assert = require('node:assert/strict')
const { once } = require('node:events')
const { createApp } = require('./app')

test('phonebook HTTP routes, validation and request logging', async t => {
  const logs = []
  const server = createApp({ logStream: { write: line => logs.push(line) } }).listen(0, '127.0.0.1')
  await once(server, 'listening')
  t.after(() => new Promise(resolve => server.close(resolve)))
  const base = `http://127.0.0.1:${server.address().port}`
  const get = path => fetch(base + path)
  const post = body => fetch(base + '/api/persons', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })

  let response = await get('/api/persons')
  assert.equal(response.status, 200)
  assert.equal((await response.json()).length, 4)
  response = await get('/api/persons/1')
  assert.equal((await response.json()).name, 'Arto Hellas')
  assert.equal((await get('/api/persons/missing')).status, 404)
  assert.equal((await get('/missing')).status, 404)
  assert.match(await (await get('/info')).text(), /info for 4 people/)

  for (const body of [{}, { name: 'Test' }, { number: '123' }, { name: '   ', number: '123' }, { name: 7, number: '123' }, { name: ' ada LOVELACE ', number: '123' }]) {
    const rejected = await post(body)
    assert.equal(rejected.status, 400)
    assert.ok((await rejected.json()).error)
  }
  response = await post({ name: ' Grace Hopper ', number: ' 555-1234 ', id: '1', admin: true })
  assert.equal(response.status, 201)
  const person = await response.json()
  assert.equal(person.name, 'Grace Hopper')
  assert.equal(person.number, '555-1234')
  assert.notEqual(person.id, '1')
  assert.deepEqual(Object.keys(person).sort(), ['id', 'name', 'number'])
  assert.match(await (await get('/info')).text(), /info for 5 people/)
  assert.deepEqual(await (await get(`/api/persons/${person.id}`)).json(), person)
  response = await fetch(base + `/api/persons/${person.id}`, { method: 'DELETE' })
  assert.equal(response.status, 204)
  assert.equal(await response.text(), '')
  assert.equal((await get(`/api/persons/${person.id}`)).status, 404)
  assert.equal((await fetch(base + `/api/persons/${person.id}`, { method: 'DELETE' })).status, 204)
  assert.equal((await (await get('/api/persons')).json()).length, 4)
  response = await fetch(base + '/api/persons', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{bad' })
  assert.equal(response.status, 400)
  assert.equal((await response.json()).error, 'invalid JSON')
  assert.ok(logs.some(line => line.includes('POST /api/persons 201') && line.includes('Grace Hopper')))
  assert.ok(logs.some(line => line.includes('GET /api/persons 200')))
})
