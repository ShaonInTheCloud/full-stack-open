const { test, before, after, beforeEach } = require('node:test')
const assert = require('node:assert/strict')
const mongoose = require('mongoose')
const { MongoMemoryServer } = require('mongodb-memory-server')
const supertest = require('supertest')
const { createApp } = require('./app')
const Person = require('./models/person')
const api = supertest(createApp({ logStream: { write: () => {} } }))
let mongo
before(async () => {
  mongo = await MongoMemoryServer.create()
  await mongoose.connect(mongo.getUri(), { dbName: 'phonebook_test' })
  await Person.init()
})
after(async () => { await mongoose.disconnect(); if (mongo) await mongo.stop() })
beforeEach(async () => { await Person.deleteMany({}); await Person.create({ name: 'Ada Lovelace', number: '040-1234567' }) })
test('reads contacts with public IDs and reports database count', async () => {
  const { body } = await api.get('/api/persons').expect(200).expect('Content-Type', /json/)
  assert.equal(body.length, 1); assert.ok(body[0].id); assert.equal(body[0]._id, undefined)
  const single = await api.get(`/api/persons/${body[0].id}`).expect(200)
  assert.equal(single.body.name, 'Ada Lovelace')
  const info = await api.get('/info').expect(200)
  assert.match(info.text, /info for 1 people/)
})
test('creates, persists, updates and deletes a contact', async () => {
  const { body } = await api.post('/api/persons').send({ name: 'Grace Hopper', number: '09-1234567' }).expect(201)
  assert.equal(await Person.countDocuments({}), 2)
  await api.put(`/api/persons/${body.id}`).send({ number: '040-9876543', name: 'Ignored' }).expect(200)
  const saved = await Person.findById(body.id)
  assert.equal(saved.number, '040-9876543'); assert.equal(saved.name, 'Grace Hopper')
  await api.delete(`/api/persons/${body.id}`).expect(204)
  assert.equal(await Person.countDocuments({}), 1)
  await api.get(`/api/persons/${body.id}`).expect(404)
  await api.put(`/api/persons/${body.id}`).send({ number: '09-1234567' }).expect(404)
  await api.delete(`/api/persons/${body.id}`).expect(404)
})
test('rejects invalid names, numbers, duplicate names and malformed JSON', async () => {
  for (const person of [{ name: 'Al', number: '09-1234567' }, { name: 'Test', number: '12345678' }, { name: 'Test', number: '1-23456789' }, { name: 'Test', number: '10-22-334455' }, { name: 'Test', number: '09-123' }, { name: 'ada lovelace', number: '09-1234567' }, { name: 42, number: '09-1234567' }, {}]) {
    const result = await api.post('/api/persons').send(person).expect(400)
    assert.ok(result.body.error)
  }
  await api.post('/api/persons').set('Content-Type', 'application/json').send('{bad').expect(400)
  assert.equal(await Person.countDocuments({}), 1)
})
test('validates updates and handles malformed IDs without changing data', async () => {
  const person = await Person.findOne({})
  await api.put(`/api/persons/${person.id}`).send({ number: 'bad' }).expect(400)
  assert.equal((await Person.findById(person.id)).number, '040-1234567')
  for (const method of ['get', 'put', 'delete']) await api[method]('/api/persons/bad-id').send({ number: '09-1234567' }).expect(400)
})
test('serves the built frontend from the backend', async () => {
  const response = await api.get('/').expect(200).expect('Content-Type', /html/)
  assert.match(response.text, /id="root"/)
})
